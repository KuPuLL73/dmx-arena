 assert.throws(()=>t.result(id,users[0],first.id,{kind:'score',winnerId:a.id,scores:[10,5],note:'Просмотрен бой'}),/готовности/);
 for(const p of [a,b])t.ready(id,{id:p.telegramId},link({id:p.telegramId}),first.id);
