const dir=fs.mkdtempSync(path.join(os.tmpdir(),'dmx-tournaments-'));
const users=Array.from({length:9},(_,i)=>({id:100+i}));
const link=user=>({telegramId:user.id,playerId:'019c24cd-e36c-7204-a5c4-'+String(user.id).padStart(12,'0'),name:'Игрок '+user.id,active:true,dataVerified:true,ownershipVerified:false});
